package loadtest

import (
	"fmt"
	"strings"
	"time"
)

// RenderMarkdown renders r as the markdown report cmd/carryon-loadtest
// writes to -out — CO-505's own "a cost report with a monthly
// estimate is reviewed and approved" validation point starts from
// this file, not from a chat message or an unsaved terminal scrollback.
func RenderMarkdown(r *Report) string {
	var b strings.Builder
	s := r.Snapshot

	fmt.Fprintf(&b, "# Carryon load/soak/cost test report\n\n")
	fmt.Fprintf(&b, "- Target: `%s`\n", r.Options.APIURL)
	fmt.Fprintf(&b, "- Developers simulated: %d\n", r.Options.Developers)
	fmt.Fprintf(&b, "- Simulated duration per developer: %s (real wall-clock time for this run: %s, speed=%.0fx)\n",
		r.Options.RunFor, r.Duration.Round(time.Second), r.Options.Speed)
	fmt.Fprintf(&b, "- Pulls/hour (team-wide): %.1f\n", r.Options.PullsPerHour)
	fmt.Fprintf(&b, "- Simulated network drop rate: %.1f%%\n\n", r.Options.NetworkDropRate*100)

	fmt.Fprintf(&b, "## Testing points (CO-505)\n\n")
	fmt.Fprintf(&b, "- No 5xx errors from Edge Functions under load, or only retried ones with zero data loss: %s\n",
		passFail(s.RebuildMismatch == 0))
	fmt.Fprintf(&b, "  - Upload attempts: %d, upload errors (after internal retries): %d\n", s.UploadAttempts, s.UploadErrors)
	fmt.Fprintf(&b, "  - Pull attempts: %d, pull errors: %d\n", s.PullAttempts, s.PullErrors)
	fmt.Fprintf(&b, "- Every simulated session rebuilds byte-identically (NFR-04): %s", passFail(s.RebuildMismatch == 0))
	if s.RebuildMismatch > 0 {
		fmt.Fprintf(&b, " — %d mismatch(es)", s.RebuildMismatch)
	}
	fmt.Fprintf(&b, "\n")
	fmt.Fprintf(&b, "- The test is scripted and repeatable (`make loadtest` / `cmd/carryon-loadtest`): yes — this report was generated by exactly that\n\n")

	fmt.Fprintf(&b, "## Measured\n\n")
	fmt.Fprintf(&b, "| Metric | Value |\n|---|---|\n")
	fmt.Fprintf(&b, "| Upload latency p50 / p95 | %s / %s |\n", s.UploadLatencyP50, s.UploadLatencyP95)
	fmt.Fprintf(&b, "| Pull latency p50 / p95 | %s / %s |\n", s.PullLatencyP50, s.PullLatencyP95)
	fmt.Fprintf(&b, "| Bytes uploaded | %d |\n", s.BytesUploaded)
	fmt.Fprintf(&b, "| Bytes downloaded (pulls) | %d |\n", s.BytesDownloaded)
	fmt.Fprintf(&b, "| Redactions applied | %d |\n\n", s.Redactions)

	fmt.Fprintf(&b, "**Not measured directly by this tool** — read from the Supabase dashboard for the real run's time window: database CPU, Storage request-latency percentiles, summary job throughput. This tool measures everything it is itself the client of (Edge Function and Storage latency/errors, as observed from the caller) — see docs/co-505-load-test.md.\n\n")

	fmt.Fprintf(&b, "## Monthly cost extrapolation (50 developers)\n\n")
	fmt.Fprintf(&b, "Extrapolated from this run's own measured per-developer traffic, scaled to 50 developers x ~21.7 working days/month x 8h/day. ")
	fmt.Fprintf(&b, "Pricing assumptions used (confirm against Supabase's and Anthropic's current pricing pages before treating this as final — CO-505's own \"required Supabase plan tier is confirmed\" validation point):\n\n")
	fmt.Fprintf(&b, "| Driver | Rate | Monthly |\n|---|---|---|\n")
	fmt.Fprintf(&b, "| Compute | $%.2f/mo flat | $%.2f |\n", r.Pricing.ComputeUSDPerMonth, r.CostEstimate.ComputeUSD)
	fmt.Fprintf(&b, "| Storage | $%.4f/GB/mo | $%.2f |\n", r.Pricing.StorageUSDPerGBMonth, r.CostEstimate.StorageUSD)
	fmt.Fprintf(&b, "| Storage requests | $%.2f/M | $%.2f |\n", r.Pricing.StorageUSDPerMillionRequests, r.CostEstimate.StorageRequestsUSD)
	fmt.Fprintf(&b, "| Edge Function invocations | $%.2f/M | $%.2f |\n", r.Pricing.EdgeFunctionUSDPerMillionInvocations, r.CostEstimate.EdgeFunctionUSD)
	fmt.Fprintf(&b, "| Anthropic (Claude Haiku, if measured separately — see note below) | — | $%.2f |\n", r.CostEstimate.AnthropicUSD)
	fmt.Fprintf(&b, "| **Total** | | **$%.2f/mo** |\n\n", r.CostEstimate.TotalUSD)

	fmt.Fprintf(&b, "**Anthropic cost note:** this run's own synthetic traffic never calls `summarize-session` (no real Claude Code session completes in a way that triggers it), so the Anthropic line above is $0 unless real token counts were supplied separately — read `ai_usage` for the real run's own time window and re-run `ExtrapolateMonthlyCost` with those counts for an accurate total; see docs/co-505-load-test.md.\n\n")

	fmt.Fprintf(&b, "## Validation points (human-gated, not self-certified)\n\n")
	fmt.Fprintf(&b, "- [ ] This cost report, with a monthly estimate, reviewed and approved\n")
	fmt.Fprintf(&b, "- [ ] The required Supabase plan tier is confirmed against the measured load above\n\n")

	if len(r.Errors) > 0 {
		fmt.Fprintf(&b, "## Non-fatal errors during this run\n\n")
		for _, e := range r.Errors {
			fmt.Fprintf(&b, "- %s\n", e)
		}
	}

	return b.String()
}

func passFail(ok bool) string {
	if ok {
		return "PASS"
	}
	return "FAIL"
}
